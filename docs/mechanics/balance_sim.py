#!/usr/bin/env python3
"""Балансная симуляция выживаемости игрока на 45 игровых дней.

Модель (детерминированная, параметры из спецификации GAME_MECHANICS.md):
- Группа: 2 персонажа (старт по плану проекта)
- 1 игровой день = 4 реальных часа; сутки = 1 тик сервера
- Потребление за сутки на персонажа: вода 2 ед., еда 1 ед. (вода вдвое быстрее еды, по Day R)
- Состояния голода: Hungry после 1 дня без еды (2 стадии), Very Hungry после 3 дней,
  Starving после 5 дней, Ext. Starving после 7 дней, смерть через 1 день без еды.
- Базовая вылазка (день 1, без прокачки): 1 персонаж, 8-10 нодов, рюкзак 20 кг.
  Дobyча (мат.ожидание по нодам локации 'Супермаркет'):
    вода 0.4 ед./нод, сырая еда 0.3 ед./нод, материалы 0.2 ед./нод, медикаменты 0.05 ед./нод
- Энергия: вылазка тратит 25% энергии персонажа; работа у станка - 10%; ночь сна - 100%.
- Крафт: Cooked Meal = 1 сырая еда + 0.5 воды + 0.25 топлива (наше упрощение TWoM-рецепта:
  TWoM: 1 raw food + 5 воды + 2 топлива -> 1 порция; пропорционально масштабируем)
"""
import random

random.seed(42)

DAYS = 45

# параметры
CHARS = 2
WATER_PER_DAY = 2.0  # ед. на персонажа (в 2 раза быстрее еды)
FOOD_PER_DAY = 1.0

# добыча за вылазку (ожидание на локацию)
# балансировка: вылазка должна давать чуть больше, чем суточное потребление 2 персонажей
# потребление в сутки: вода 4 ед., еда 2 ед. -> добыча за вылазку (9 нодов):
# вода 0.55/нод (=4.95) чтобы вода была дефицитной но компенсируемой;
# сырая еда 0.35/нод (=3.15) — почти покрывает еду, остальное из торговли/ловушек
LOOT = {"water": 0.55 * 9, "raw_food": 0.38 * 9, "materials": 0.2 * 9, "meds": 0.05 * 9}

# пассивный источник (ловушка на мелкую живность, строится к ~дню 3):
# 2 сырья за 1-3 дня -> в среднем 1 ед./сутки сырой еды (по TWoM: 2xRaw Food из 1 bait)
TRAP_PER_DAY = 1.0

inventory = {"water": 10.0, "raw_food": 6.0, "materials": 20.0, "fuel": 2.0, "meds": 1}
# топливо производится из дерева на печи: 4 дерева -> 1 топливо (симулируем как доступность)
# в симуляции считаем, что игрок поддерживает топливо из добытых материалов (дрова)
inventory["fuel_income"] = 0.3  # ед. топлива в сутки из дров (вылазка даёт дрова в материалах)
hunger_days = [0, 0]  # дней без еды у каждого персонажа
fed = False  # кормим раз в 2 дня по стратегии TWoM

events = []
for day in range(1, DAYS + 1):
    # утренний тик: потребление
    for i in range(CHARS):
        inventory["water"] -= WATER_PER_DAY
        inventory["raw_food"] -= FOOD_PER_DAY
        hunger_days[i] += 1
    inventory["fuel"] += 0.3  # производство топлива из дров

    # дневные действия: готовка — кормим самых голодных (стратегия TWoM: раз в 2 дня)
    meals = 0
    while inventory["raw_food"] >= 1 and inventory["water"] >= 0.5 and inventory["fuel"] >= 0.25 and meals < CHARS:
        inventory["raw_food"] -= 1
        inventory["water"] -= 0.5
        inventory["fuel"] -= 0.25
        meals += 1

    fed_ids = sorted(range(CHARS), key=lambda i: -hunger_days[i])
    for i in fed_ids:
        if meals > 0 and hunger_days[i] >= 1:
            meals -= 1
            hunger_days[i] = 0

    # ночь: вылазка (1 локация, 1 персонаж) + пассивный доход ловушки
    if day >= 3:
        inventory["raw_food"] += TRAP_PER_DAY
    raid = {k: random.uniform(0.6, 1.4) * v for k, v in LOOT.items()}
    for k, v in raid.items():
        inventory[k] = inventory.get(k, 0) + v

    # проверка смерти
    dead = 0
    for i in range(CHARS):
        if hunger_days[i] >= 8:
            dead += 1
    if dead > 0:
        events.append(f"ДЕНЬ {day}: ПОТЕРЯ {dead} ПЕРСОНАЖА(ЕЙ) — смерть от голода")
        break

    if day % 7 == 1:
        print(f"День {day:3d}: вода={inventory['water']:5.1f} еда(сырая)={inventory['raw_food']:5.1f} "
              f"материалы={inventory['materials']:5.1f} топливо={inventory['fuel']:5.1f} meds={inventory['meds']:.2f}")

print("\nСобытия:", events if events else "ни одного персонажа не потеряно за 45 дней")

# прогноз ресурсов на 45 дней (средние значения)
print("\n--- Итоги симуляции ---")
print(f"Выживаемость 2 персонажей на 45 дней: {'ДА' if not events else 'НЕТ'}")
